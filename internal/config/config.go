// LotelDir is the base directory for all lotel state and data.
const LotelDir = ".lotel"

// DefaultConfigName is the embedded config file written when no custom config is found.
const DefaultConfigName = "collector-config.yaml"

const ManagedConfigHeader = "# lotel-managed-config v3 - regenerated by lotel; put custom config in ./lotel-collector.yaml"
const managedConfigVersion = 3

var Notices io.Writer = os.Stderr
var managedHeader = regexp.MustCompile(`^# lotel-managed-config v(\d+)( |$)`)

