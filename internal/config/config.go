// ResolvePaths returns the config file path and data directory path.
// It looks for a config in the current working directory first, then
// falls back to a default config in ~/.lotel/.
func ResolvePaths() (configPath, dataPath string, err error) {
	return ResolvePathsWithConfig("")
}

func ResolvePathsWithConfig(override string) (configPath, dataPath string, err error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", "", fmt.Errorf("getting home directory: %w", err)
	}

	dataPath = filepath.Join(home, LotelDir, "data")
	for _, sub := range []string{"traces", "metrics", "logs", "profiles"} {
		if err := os.MkdirAll(filepath.Join(dataPath, sub), 0o755); err != nil {
			return "", "", fmt.Errorf("creating data subdirectory %s: %w", sub, err)
		}
	}

	if override != "" {
		configPath, err = filepath.Abs(override)
		if err != nil {
			return "", "", err
		}
		managed := filepath.Join(home, LotelDir, DefaultConfigName)
		if configPath == managed {
			if err := refreshManagedConfig(configPath); err != nil {
				return "", "", err
			}
		}
		if _, err := os.Stat(configPath); err != nil {
			return "", "", fmt.Errorf("collector config: %w", err)
		}
		return configPath, dataPath, nil
	}

	// Look for config in CWD first (project-local config).
	cwd, err := os.Getwd()
	if err == nil {
		candidate := filepath.Join(cwd, "lotel-collector.yaml")
		if _, err := os.Stat(candidate); err == nil {
			return candidate, dataPath, nil
		}
	}

	// Fall back to ~/.lotel/collector-config.yaml, creating it with defaults if absent.
	lotelDir := filepath.Join(home, LotelDir)
	if err := os.MkdirAll(lotelDir, 0o755); err != nil {
		return "", "", fmt.Errorf("creating lotel directory: %w", err)
	}
	configPath = filepath.Join(lotelDir, DefaultConfigName)
	if err := refreshManagedConfig(configPath); err != nil {
		return "", "", err
	}

	return configPath, dataPath, nil
}

// DataPath returns the data directory path.
func DataPath() (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", fmt.Errorf("getting home directory: %w", err)
	}
	return filepath.Join(home, LotelDir, "data"), nil
}

// refreshManagedConfig upgrades only the home-managed configuration.
func refreshManagedConfig(path string) error {
	data, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if err == nil {
		match := managedHeader.FindStringSubmatch(strings.SplitN(string(data), "\n", 2)[0])
		if match != nil {
			version, parseErr := strconv.Atoi(match[1])
			if parseErr != nil {
				return fmt.Errorf("invalid managed config version: %w", parseErr)
			}
			if version >= managedConfigVersion {
				if version > managedConfigVersion {
					fmt.Fprintf(Notices, "lotel: collector config v%d is newer than this lotel (v%d)\n", version, managedConfigVersion)
				}
				return nil
			}
		} else {
			backup := fmt.Sprintf("%s.bak.%d", path, time.Now().UnixNano())
			if err := os.WriteFile(backup, data, 0o600); err != nil {
				return err
			}
			fmt.Fprintf(Notices, "lotel: replaced ~/.lotel/collector-config.yaml (backup: %s); put custom config in ./lotel-collector.yaml (see README#genai)\n", backup)
		}
	}
	if err := os.WriteFile(path+".tmp", []byte(DefaultConfig), 0o644); err != nil {
		return err
	}
	return os.Rename(path+".tmp", path)
}
